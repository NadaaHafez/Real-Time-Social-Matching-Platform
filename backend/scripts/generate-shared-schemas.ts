import * as fs from "fs";
import * as path from "path";

import { getDMMF } from "@prisma/internals";

/**
 * Writes Zod schemas for every Prisma enum and model into the shared package.
 *
 *   yarn prisma:generate
 *
 * The database schema is the single source for enums, so `UserStatus` is declared once in
 * schema.prisma and nowhere else. The hand-written wire schemas in packages/shared/src/schemas
 * import these instead of repeating the values.
 *
 * What it generates:
 *  - Enums are `z.enum`, so each one is a schema (validates, documents) *and* a value
 *    object (`UserStatus.active`) *and* a type, all from one declaration.
 *  - Models are scalars only, suffixed `Model` (`userModelSchema`, `UserModel`). They are
 *    the database shape — Date objects, internal columns — so wire schemas `.pick()` from
 *    them rather than exposing them directly, and the suffix keeps the names free for DTOs.
 *    Relations are left out: z.lazy() cycles collapse to ZodTypeAny and lose their types.
 *  - `///` doc comments become both JSDoc and `.describe()`, so they reach the editor and
 *    the OpenAPI document.
 */

type Dmmf = Awaited<ReturnType<typeof getDMMF>>;
type Model = Dmmf["datamodel"]["models"][number];
type Field = Model["fields"][number];
type Enum = Dmmf["datamodel"]["enums"][number];

const SCHEMA_PATH = path.resolve(__dirname, "../prisma/schema.prisma");
const OUTPUT_PATH = path.resolve(__dirname, "../../packages/shared/src/generated/prisma.ts");

const lowerFirst = (name: string) => name.charAt(0).toLowerCase() + name.slice(1);

function jsDoc(doc: string | undefined, indent = ""): string {
  if (!doc) return "";
  const lines = doc.replace(/\*\//g, "*\\/").split("\n");
  return `${indent}/**\n${lines.map((line) => `${indent} * ${line}`.trimEnd()).join("\n")}\n${indent} */\n`;
}

const describe = (doc: string | undefined) => (doc ? `.describe(${JSON.stringify(doc)})` : "");

function scalarToZod(field: Field): string {
  if (field.kind === "enum") return `${lowerFirst(field.type)}Schema`;

  switch (field.type) {
    case "String":
      return "z.string()";
    case "Int":
      return "z.number().int()";
    case "Float":
      return "z.number()";
    case "Boolean":
      return "z.boolean()";
    case "DateTime":
      return "z.date()";
    case "BigInt":
      return "z.bigint()";
    case "Json":
      return "z.unknown()";
    case "Bytes":
      return "z.instanceof(Uint8Array)";
    // Prisma hands back a Decimal.js instance. z.number() would claim a type it isn't.
    case "Decimal":
      return "z.custom<{ toNumber(): number; toString(): string }>()";
    default:
      return "z.unknown()";
  }
}

function fieldToZod(field: Field): string {
  let expr = scalarToZod(field);
  if (field.isList) expr = `z.array(${expr})`;
  else if (!field.isRequired) expr = `${expr}.nullable()`;
  return expr + describe(field.documentation);
}

function generateEnum(prismaEnum: Enum): string {
  const name = prismaEnum.name;
  const schema = `${lowerFirst(name)}Schema`;
  const values = prismaEnum.values.map((value) => JSON.stringify(value.name)).join(", ");

  return (
    jsDoc(prismaEnum.documentation) +
    `export const ${schema} = z.enum([${values}])${describe(prismaEnum.documentation)};\n` +
    `export type ${name} = z.infer<typeof ${schema}>;\n` +
    `export const ${name} = ${schema}.enum;\n`
  );
}

function generateModel(model: Model): string {
  const schema = `${lowerFirst(model.name)}ModelSchema`;
  const fields = model.fields
    .filter((field) => field.kind !== "object")
    .map((field) => `${jsDoc(field.documentation, "  ")}  ${field.name}: ${fieldToZod(field)},`)
    .join("\n");

  return (
    jsDoc(model.documentation) +
    `export const ${schema} = z.object({\n${fields}\n})${describe(model.documentation)};\n` +
    `export type ${model.name}Model = z.infer<typeof ${schema}>;\n`
  );
}

async function main() {
  const dmmf = await getDMMF({ datamodel: fs.readFileSync(SCHEMA_PATH, "utf-8") });
  const { enums, models } = dmmf.datamodel;

  const output = [
    "// This file is generated by backend/scripts/generate-shared-schemas.ts. Do not edit.",
    "// Source: backend/prisma/schema.prisma. Run `yarn prisma:generate` to refresh.",
    "",
    'import { z } from "zod";',
    "",
    "// ============================================================================",
    "// ENUMS",
    "// ============================================================================",
    "",
    enums.map(generateEnum).join("\n"),
    "// ============================================================================",
    "// MODELS (database shape: scalars only, Date objects)",
    "// ============================================================================",
    "",
    models.map(generateModel).join("\n"),
    "// ============================================================================",
    "// OPENAPI COMPONENTS",
    "// ============================================================================",
    "",
    "// Enums only. Models are the database shape and never go over the wire as-is.",
    "export const prismaEnumSchemaComponents = {",
    ...enums.map((e) => `  ${e.name}: ${lowerFirst(e.name)}Schema,`),
    "};",
    "",
  ].join("\n");

  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, output, "utf-8");

  console.log(`Generated ${enums.length} enums + ${models.length} models -> ${OUTPUT_PATH}`);
}

main().catch((err) => {
  console.error("Failed to generate shared schemas:", err);
  process.exit(1);
});
